namespace NV.Shared.Contracts.Enums
{
    /// 룸의 진행 단계. 서버가 소유하고 클라이언트는 통보받는다.
    ///
    /// `Shared` 에 있는 이유는 클라이언트가 이 값으로 화면을 고르기 때문이다 —
    /// 로비를 그릴지 게임 씬을 열지가 여기서 갈린다. 단계를 바꾸는 판단은
    /// 서버에만 있고, 클라이언트는 받은 값을 표시할 뿐이다.
    public enum RoomPhase : byte
    {
        /// 명단을 모으는 중. 시뮬레이션하지 않고 스냅샷도 보내지 않는다.
        Waiting = 0,

        /// 매치 진행 중. 이 단계에서만 입력을 처리하고 스냅샷을 보낸다.
        Playing = 1,

        /// 결과 화면. 방장이 로비로 되돌리면 다시 `Waiting` 이 된다.
        Ended = 2,
    }
}
