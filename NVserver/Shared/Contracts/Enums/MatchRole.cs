namespace NV.Shared.Contracts.Enums
{
    /// 매치에서 어느 편인가. 서버가 정하고 클라이언트는 통보받는다.
    ///
    /// 기획서 §2 — 술래 한 명과 다수의 플레이어다. 정확히 한 명이 `Seeker` 이고
    /// 나머지가 전부 `Runner` 다.
    ///
    /// 이름이 `Role` 이 아닌 이유는 충돌을 미리 피하기 위해서다. 클라이언트에 이미
    /// `NV.Game.Role` 이 있고, `MatchPhase` 를 `Shared` 에 넣었을 때 같은 이름이 겹쳐
    /// 호출부를 수식해야 했다. 값은 그 열거형과 같으므로 전문을 받는 쪽에서 그대로 옮긴다.
    public enum MatchRole : byte
    {
        /// 아직 배정되지 않았다. 로비에 이 상태가 있어야 화면이 거짓말을 하지 않는다.
        Unassigned = 0,

        /// 기획서 §2.2 — 무기가 없고 열쇠를 모아 탈출한다.
        Runner = 1,

        /// 기획서 §2.1 — 총기를 쓰고 탈출을 저지한다. 매치당 한 명이다.
        Seeker = 2,
    }
}
