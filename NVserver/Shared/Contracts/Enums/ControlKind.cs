namespace NV.Shared.Contracts.Enums
{
    /// `MessageOpcode.Control` 의 두 번째 바이트. 클라이언트가 룸에 요청하는 행위다.
    ///
    /// 요청이지 명령이 아니다. 서버는 요청자가 방장인지, 지금 단계에서 가능한
    /// 전이인지 다시 판단한다. 클라이언트가 보낸 것만으로 룸 상태가 바뀌는 경로는 없다.
    public enum ControlKind : byte
    {
        None = 0,

        /// 방장이 매치 시작을 요청한다. 최소 인원 미달이면 서버가 무시한다.
        StartMatch = 1,

        // 2 는 비어 있다. 자발적 퇴장을 여기 두었다가 뺐다 — 퇴장은 WebSocket
        // 정상 종료(NormalClosure) 프레임으로 이미 구분되고, 제어 메시지로도 보내면
        // 같은 소켓에 두 개의 송신이 겹친다. WebSocket 은 동시 송신을 허용하지 않는다.

        /// 매치가 끝났다고 방장이 보고한다. value 에 결과 코드를 싣는다.
        ///
        /// 결과를 판정한 것은 방장 클라이언트다. 매치 규칙이 아직 클라이언트에
        /// 있는 동안의 한시적 경로이며, 서버는 중계만 한다. 규칙이 서버로 오면
        /// 이 종류는 사라진다.
        EndMatch = 3,

        /// 결과 화면에서 로비로 되돌린다. 방장만 가능하다.
        ReturnToLobby = 4,

        /// 대기방에서 준비를 켜거나 끈다. value 는 0 또는 1 이다.
        ///
        /// **방장은 보내지 않는다.** 시작 버튼을 누르는 것이 방장의 준비이고, 둘 다 두면
        /// 같은 뜻의 조작이 두 개가 된다. 서버는 방장이 보낸 것도 받아 적기는 하지만
        /// 시작 조건에서 방장의 준비를 보지 않는다.
        SetReady = 5,
    }
}
