namespace NV.Shared.Contracts.Enums
{
    /// `MessageOpcode.Event` 의 두 번째 바이트. 이벤트 종류를 가른다.
    ///
    /// opcode 를 종류마다 새로 만들지 않는다. 서버 발신 opcode 는 상위 비트로
    /// 구분되는 좁은 공간이고, 이벤트는 앞으로 늘어나는 쪽이다.
    public enum EventKind : byte
    {
        None = 0,

        /// 룸의 현재 상태 전문. 단계·방장·명단·역할·배치 씨드가 전부 들어 있다.
        RoomState = 1,

        /// 매치의 현재 상태 전문. 단계·시계·열쇠·탈출·참가자별 상태가 들어 있다.
        ///
        /// `RoomState` 와 성격은 같지만(전문, 2Hz, 멱등) **본문이 수신자에 따라 다르다** —
        /// Seeker 사본에서는 열쇠 진행도가 0 으로 채워진다. 그래서 스냅샷처럼 세션별로
        /// 인코딩한다.
        MatchState = 2,

        /// 목표물의 현재 배치 — 제단·문·열쇠·장치.
        ///
        /// **Seeker 사본에서는 문 블록이 빠진다.** 0 으로 채우는 것으로는 부족하다 — 그것도
        /// "문이 있다" 는 사실을 알려 준다. `MatchState` 보다 한 걸음 더 나간 필터이며,
        /// 이것이 씨드 공유로는 닫을 수 없던 정보 누출을 닫는다.
        ///
        /// 주기가 다르다. 배치는 매치 중에 거의 바뀌지 않으므로(열쇠가 주워질 때만) 2Hz 가
        /// 아니라 **변경 즉시 + 5초**로 보낸다 — 176B 를 2Hz 로 8명에게 보내면 2.8KB/s 가
        /// 더 붙고, 그만큼의 정보가 없다.
        ObjectiveState = 3,

        /// 총알 한 발이 발사됐다. 사수·시작점·시선·틱이 들어 있다.
        ///
        /// **이 프로젝트의 유일한 알림이다.** 위의 셋은 전부 전문 — 멱등한 현재 상태를 반복하며,
        /// 세션 채널이 `Bounded(32, DropOldest)` 라 한 번짜리 메시지가 사라질 수 있기 때문에
        /// 그렇게 설계했다. 발사는 **상태가 아니라 사건**이므로 그 틀에 맞지 않는다.
        ///
        /// 놓쳐도 되는 이유는 **결과가 전문으로 따라오기** 때문이다 — 피격·사망·탄약은 전부
        /// 서버 판정이고 `MatchState` 와 스냅샷으로 온다. 잃는 것은 예광탄 하나다.
        ///
        /// 새 알림을 추가하고 싶을 때의 기준은 그것이다: **놓쳤을 때 틀린 상태가 남는가.**
        /// 남으면 전문이어야 한다. 근거는 ADR 0003.
        FireEvent = 4,
    }
}
