namespace NV.Shared.Contracts.Enums
{
    /// 매치의 진행 단계. 서버가 소유하고 클라이언트는 통보받는다.
    ///
    /// **`RoomPhase` 와 다른 축이다.** 그쪽은 룸의 생애(명단을 모으는 중 / 진행 중 /
    /// 결과 화면)이고, 이것은 그 안에서 매치가 어디까지 왔는지다. 룸이 `Playing` 인
    /// 동안에도 매치는 역할 공개 중일 수 있고, 그 구간에서는 이동이 잠긴다.
    ///
    /// 두 축을 하나로 합치지 않는 이유는 `Room.Advance` 가 이미 `RoomPhase.Playing`
    /// 에서만 시뮬레이션하기 때문이다. 매치 단계를 그 축에 끼워 넣으면 "역할 공개 중"
    /// 이 시뮬레이션을 멈추는 단계가 되어, 그 4초 동안 중력도 멈춘다.
    ///
    /// 값은 클라이언트의 `NV.Game.MatchPhase` 와 같다. 클라이언트가 자기 열거형을
    /// 그대로 쓰고 있어서 지금은 두 벌이지만, 값이 같으므로 전문을 받는 쪽에서
    /// 그대로 옮길 수 있다 — 통합은 클라이언트가 뷰로 바뀔 때(IG-010) 한다.
    public enum MatchPhase : byte
    {
        /// 아직 시작하지 않았다. 역할이 정해지지 않은 상태다.
        Lobby = 0,

        /// 역할 공개. 시계는 아직 흐르지 않고 이동이 잠긴다.
        RoleReveal = 1,

        /// 진행 중. 매치 시계가 줄어든다.
        Playing = 2,

        /// 끝났다. 결과가 정해져 있다.
        Ended = 3,
    }
}
