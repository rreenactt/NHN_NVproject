using System;

namespace NV.Shared.Contracts.Enums
{
    /// EntityState 의 flags 필드. 8비트를 넘기지 않는다.
    ///
    /// **두 종류가 한 바이트에 섞여 있고, 채우는 주체가 다르다.**
    ///
    /// 아래 세 개는 이동 시뮬레이션이 소유한다. `PlayerMovement.Step` 이 매 틱 계산하고
    /// 클라이언트도 예측으로 같은 값을 만든다 — `PlayerState.Flags` 에 들어 있다.
    ///
    /// `Bleeding` 부터는 **매치 판정이 소유하며 서버만 안다.** 그래서 `PlayerState` 에
    /// 두지 않는다 — 그 구조체는 결정적 시뮬레이션 상태이고 `StateHash` 에 들어가는데,
    /// 클라이언트는 이 비트들을 예측할 수 없으므로 해시 비교가 영구히 어긋난다.
    /// 서버는 이 비트를 `PlayerEntity.MatchFlags` 에 따로 들고 있다가 스냅샷을 인코딩할
    /// 때 합친다(`StateProjection.ToEntityState` 의 3인자 오버로드).
    ///
    /// **매 틱 필요한 것만 여기 온다.** 매치 상태 전문(`MatchState`)은 2Hz 이므로, 출혈처럼
    /// 원격 몸의 표현이 즉시 따라가야 하는 것을 그쪽에 두면 피 흔적이 최대 0.5초 늦게
    /// 시작한다. 반대로 열쇠 수처럼 2Hz 로 충분한 것은 여기 두지 않는다 — 8비트가 좁다.
    [Flags]
    public enum EntityFlags : byte
    {
        None = 0,

        // ---- 이동 시뮬레이션이 소유한다 (클라이언트도 예측한다)
        Alive = 1 << 0,
        OnGround = 1 << 1,
        Crouching = 1 << 2,

        // ---- 매치 판정이 소유한다 (서버만 안다)

        /// 기획서 §4.1 — 1회 피격 상태. 이동 중 피 흔적을 남긴다(§4.2).
        ///
        /// 매 틱 필요하다. 흔적을 그리는 것은 클라이언트이고, 그 판단이 늦으면 흔적이
        /// 끊겨 보인다. 채우는 것은 피격이 서버 판정이 될 때다(IG-014).
        Bleeding = 1 << 3,

        /// 이 몸이 술래다. 기획서 §2.1 — 총기를 든다.
        ///
        /// 매 틱 필요한 이유는 원격 몸의 무기 유무가 이 비트로 갈리기 때문이다.
        /// 룸 상태 전문의 `SeekerPlayerId` 로도 알 수 있지만, 그것은 명단이고 이것은 몸이다.
        Seeker = 1 << 4,

        /// 문으로 빠져나갔다. 기획서 §6.
        ///
        /// 탈출한 몸은 화면에서 사라지지만 명단에는 남는다 — 승리 조건이 그 수를 센다.
        /// 채우는 것은 탈출이 서버 판정이 될 때다(IG-012).
        Escaped = 1 << 5,

        /// 이동이 잠겼다. 역할 공개 중이거나(기획서 §3) 정지 장치가 걸렸다(§5.1).
        ///
        /// 서버는 잠금을 입력 무력화로 구현하므로 클라이언트가 이 비트를 모르면 자기
        /// 입력으로 계속 예측하고, 리컨실리에이션이 매 틱 되돌린다 — 증상은 잠긴 동안
        /// 화면이 떨리는 것이다.
        Frozen = 1 << 6,

        /// 기획서 §4.1 — 2회 피격으로 쓰러졌다.
        ///
        /// **`Alive` 와 다른 것이다.** 그쪽은 이동 시뮬레이션의 것이고 클라이언트가 예측하며
        /// `PlayerState.Flags` 에 들어가 `StateHash` 를 이룬다 — 매치 판정으로 그 비트를 내리면
        /// 클라이언트가 예측할 수 없는 값이 해시에 섞여 리컨실리에이션이 영구히 어긋난다.
        /// 그래서 쓰러짐은 **합쳐지는 쪽**(`MatchFlags`)에 별도 비트로 둔다.
        ///
        /// 매 틱 필요하다. 몸이 사라지는 것은 즉시 보여야 하고, 2Hz 전문의
        /// `MatchParticipant.Hits` 로 판단하면 최대 0.5초 늦는다(탈출이 같은 이유로
        /// 여기 있다).
        ///
        /// **이것이 마지막 비트다.** 다음 매치 상태를 매 틱 보내야 한다면 `EntityFlags` 를
        /// 늘리는 것이 아니라 무엇이 정말 매 틱 필요한지 다시 봐야 한다.
        Downed = 1 << 7,
    }
}
