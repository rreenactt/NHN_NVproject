namespace NV.Shared.Contracts.Enums
{
    /// 명단 한 줄의 상태 비트. `EventKind.RoomState` 의 항목마다 1바이트.
    ///
    /// 대기방에서 **한 사람에 대해 참/거짓으로 답하는 것**을 여기 모은다. 세는 값
    /// (인원·준비 인원)은 넣지 않는다 — 명단에서 세면 되고, 헤더에 유도 가능한 값을
    /// 두면 두 값이 어긋날 수 있는 상태가 표현 가능해진다.
    ///
    /// 스냅샷의 <see cref="EntityFlags"/> 와 성격이 다르다. 그쪽은 **몸의 겉모습**이
    /// 즉시 따라가야 하는 것이라 매 틱 가고, 이쪽은 대기방 화면이 반 초 늦어도 되는
    /// 것이라 2Hz 전문에 실린다. 어느 쪽에 두는지는 설계 결정이며 섞으면 둘 다 잘못된다.
    ///
    /// 비트가 남아 있다. 팀·관전자가 그 자리에 들어간다.
    [System.Flags]
    public enum RoomPlayerFlags : byte
    {
        None = 0,

        /// 이 사람이 준비를 눌렀다. 방장은 누르지 않는다 — 시작 버튼이 방장의 준비다.
        Ready = 1 << 0,

        /// 사람이 아니다. 서버가 채운 참가자다(`BotOptions`, 정적 룸 한정).
        ///
        /// 서버는 이것을 이미 알고 있었고(`PlayerEntity.IsBot`) 클라이언트는 알 방법이
        /// 없었다. 이름으로 짐작하게 두면 `BOT 1` 이라고 스스로 이름을 지은 사람과
        /// 구분되지 않는다.
        Bot = 1 << 1,
    }
}
