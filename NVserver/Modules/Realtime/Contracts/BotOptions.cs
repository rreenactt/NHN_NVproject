namespace NV.Realtime.Contracts
{
    /// 봇 참가자 설정. 개발 인원이 한 명일 때 매치를 끝까지 돌리기 위한 것이다.
    ///
    /// **정적 룸에서만 동작한다.** 편의가 아니라 두 가지 구조가 그렇게 만든다.
    ///
    /// - `RoomRegistry.Sweep` 은 참가자가 있는 룸을 회수하지 않는다. 봇이 사람처럼
    ///   세어지므로 초대 코드 룸에 봇이 남으면 그 룸이 영구히 살아남는다. 정적 룸은
    ///   애초에 회수 대상이 아니라 이 문제가 없다.
    /// - `Room.IsAuthorized` 는 정적 룸에서 전원에게 시작 권한을 준다. 봇 채우기와
    ///   역할 희망 같은 개발용 훅이 그 경계 안에만 있으면 실제 매치의 판정에 닿지 않는다.
    ///
    /// **프로덕션 설정에서 기본값이 꺼짐인 것이 이 기능의 방어선이다.** 정적 룸 한정과
    /// 겹쳐 두 겹이 된다 — `Game:StaticRooms` 가 비어 있는 배포에서는 켜져 있어도 봇이
    /// 생길 룸이 없다. `NetworkConditionsEnabled` 와 같은 취급이다.
    public sealed class BotOptions
    {
        public bool Enabled { get; set; }

        /// 참가자를 몇 명까지 채우는가. 0 이면 매치 시작 최소 인원까지다.
        ///
        /// 상한은 룸 정원이며 모듈이 자른다 — 정원 상수는 `internal` 이고, 설정 타입이
        /// 그것을 알면 용량 상수가 공개 표면으로 새어 나온다.
        ///
        /// 기본값(2)이 정원(8)보다 훨씬 작은 것이 의도다. 봇이 슬롯을 다 차지하면
        /// 두 번째 사람이 붙을 때 정원 초과로 거절된다.
        public int FillTo { get; set; }

        /// **봇이** 맡을 역할. 사람이 맡을 역할은 그 반대다.
        ///
        /// 기본값이 `Runner` 인 이유는 검증 대상이다 — 사람이 술래여야 발사·피격·출혈·
        /// 순간이동·사망을 화면에서 확인할 수 있고, 서 있는 봇이 그 표적이다.
        public BotRolePreference Role { get; set; } = BotRolePreference.Runner;
    }

    /// 봇에게 어느 역할을 주기를 바라는가. 희망이며 보장이 아니다 —
    /// 지킬 수 없으면 `Room` 이 무작위로 떨어지고 그 사실을 로그로 남긴다.
    public enum BotRolePreference
    {
        /// 지금까지와 같은 무작위 선정.
        Any = 0,

        /// 봇이 Runner 다. 술래는 사람 중에서 고른다.
        Runner = 1,

        /// 봇이 술래다. 사람은 도망치는 쪽이 된다.
        Seeker = 2,
    }
}
