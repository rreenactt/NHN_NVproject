namespace NV.Realtime.Contracts
{
    /// 요청 제한 정책 이름. 모듈이 자기 엔드포인트에 붙이고 Api 가 내용을 등록한다.
    ///
    /// 이름만 모듈에 두는 이유: 어느 엔드포인트에 제한이 필요한지는 모듈이 알고,
    /// 몇 번까지 허용할지와 어떤 기준으로 나눌지는 배포 환경의 일이다.
    ///
    /// 이 제한이 동시 룸 수 상한을 대신한다. 상한은 임의의 쿼리스트링으로 룸이 무한히
    /// 생기던 시절의 방어선이었고, 룸이 `POST /rooms` 로만 생기는 지금 막아야 하는
    /// 것은 룸의 개수가 아니라 요청의 속도다.
    public static class RateLimitPolicies
    {
        /// 방 만들기. 룸 하나가 메모리를 차지하고 비어도 60초 동안 회수되지 않으므로
        /// 이 제한이 곧 한 클라이언트가 잡아 둘 수 있는 룸 수의 상한이 된다.
        public const string RoomCreate = "rooms-create";

        /// 코드를 하나 시도하는 것. 참가 전 조회(`GET /rooms/{code}`)와 접속(`/ws`)에
        /// 같은 정책을 붙인다.
        ///
        /// 둘을 같은 양동이에 두는 이유가 있다. 조회만 막으면 조회를 건너뛰고 접속으로
        /// 코드를 찍을 수 있다 — `/ws` 도 없는 코드에 404, 정원 초과에 503 으로 답하므로
        /// 맞는 코드를 가려내는 데 충분하다. 룸 수 상한이 사라진 뒤로는 코드가 남의 방을
        /// 막는 유일한 수단이므로, 시도 횟수를 제한하는 자리가 한 곳이어야 한다.
        ///
        /// 사람이 코드를 받아 적고 들어오는 데는 몇 번이면 충분하고, 끊긴 접속의 자동
        /// 재시도(4회)까지 감안해도 남는 값이어야 한다.
        public const string CodeAttempt = "code-attempt";

        /// 공개 방 목록 조회(`GET /rooms`).
        ///
        /// 코드 시도와 **다른** 양동이를 쓴다. 목록은 로비 화면이 반복해서 부르는 것이고,
        /// 그것이 같은 양동이를 쓰면 새로고침을 몇 번 누른 사람이 정작 방에 들어갈 예산을
        /// 스스로 깎는다. 시도 횟수를 한 곳에 모아야 하는 것은 *코드를 찍어 보는* 경로이고,
        /// 목록은 코드를 찍는 수단이 아니다 — 거기 실리는 방은 이미 공개를 선택한 방이다.
        ///
        /// 이 정책은 목록이 설정 뒤에서 나오면서 생겼다. 그전에는 개발 설정에서만 열려
        /// 제한이 없었다.
        public const string RoomList = "rooms-list";
    }
}
