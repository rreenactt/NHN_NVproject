using System.Text;
using NV.Shared.Collision;

namespace NV.Client.EditorTools.Writers
{
    /// 맵 자료를 파일 바이트로 옮긴다.
    ///
    /// **지금 구현은 하나다.** 그런데도 인터페이스가 있는 이유는 "구현이 하나뿐인 인터페이스를
    /// 만들지 않는다" 는 이 저장소의 규칙과 부딪히지 않는다 — 이 자리는 포맷이 늘어날 자리로
    /// 요구사항에 명시되어 있고, 인터페이스가 하는 일은 **`MapExportPipeline` 이 문자열을
    /// 전제하고 있다는 사실을 눈에 보이게 만드는 것**이다. 원자적 쓰기, "내용이 같으면 쓰지
    /// 않는다", `\r\n` 정규화가 전부 문자열 기준으로 짜여 있고, 바이너리를 넣으려면 그 셋을
    /// 먼저 바이트 기준으로 옮겨야 한다. 그 일이 얼마인지 여기 적어 둔다.
    ///
    /// **바이너리 구현을 지금 만들지 않는다.** 지금 맵 파일은 736 박스에 70KB 이고 서버가 기동할
    /// 때 한 번 읽는다. 줄여서 얻는 것이 없다. 대형 맵이 생기면 그때 이 자리에 넣는다 — 다만
    /// 그때 먼저 무너지는 것은 파일 크기가 아니라 서버의 브로드페이즈 없는 겹침 해소다.
    public interface IMapWriter
    {
        /// 파일 확장자. 점을 포함한다.
        string Extension { get; }

        /// 사람이 읽을 이름.
        string Describe { get; }

        /// 텍스트로 쓸 수 있는 포맷인가.
        ///
        /// `MapExportPipeline` 의 비교·정규화·원자적 쓰기가 문자열 위에 있으므로, 지금 그 경로를
        /// 탈 수 있는 것은 이쪽뿐이다. 거짓을 돌려주는 구현이 생기면 그 경로부터 고쳐야 한다.
        bool IsText { get; }

        /// 맵을 쓴다.
        void Write(StringBuilder into, MapData data);
    }
}
